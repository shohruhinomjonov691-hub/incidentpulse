/**
 * Renders the sudoers allowlist for the runner from the policy file, so the two can never drift.
 *
 *   node scripts/render-sudoers.ts /etc/incidentpulse/actions-policy.json > /tmp/incidentpulse-actions.sudoers
 *   visudo -cf /tmp/incidentpulse-actions.sudoers && install -m 0440 ... /etc/sudoers.d/incidentpulse-actions
 *
 * Every line is an exact command (no wildcard) except the nginx_site_proxy helper, which takes a
 * 4- or 5-digit loopback port and is re-validated by the helper itself.
 */
import { readFileSync } from "node:fs";
import { privilegedSteps, siteHelperRules } from "../src/commands.ts";
import { type Policy, parsePolicy } from "../src/policy.ts";

export const RUNNER_USER = "incidentpulse-actions";

/** sudoers(5): `,` `:` `=` and `\` must be escaped inside a command line. */
const escapeArg = (arg: string) => arg.replace(/([,:=\\])/g, "\\$1");

export function renderSudoers(policy: Policy, user = RUNNER_USER): string {
  const lines = new Set<string>();
  for (const step of privilegedSteps(policy)) {
    lines.add([policy.bins[step.bin], ...step.args.map(escapeArg)].join(" "));
  }
  // The helper rules are already escaped (they contain a deliberate pattern).
  for (const rule of siteHelperRules(policy)) lines.add(rule);

  const body = [...lines]
    .sort()
    .map((line) => `    ${line}`)
    .join(", \\\n");
  return `# Generated by host/actions-runner/scripts/render-sudoers.ts from the runner policy. Do not edit by hand.
# ${lines.size} exact commands. Anything not listed here is refused by sudo.
Defaults:${user} !requiretty, !lecture, secure_path="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
Defaults:${user} logfile="/var/log/incidentpulse-sudo.log"
Cmnd_Alias INCIDENTPULSE_RUNBOOKS = \\
${body}
${user} ALL=(root) NOPASSWD: INCIDENTPULSE_RUNBOOKS
`;
}

if (process.argv[1]?.endsWith("render-sudoers.ts")) {
  const path = process.argv[2];
  if (!path) {
    console.error("usage: render-sudoers.ts <policy.json>");
    process.exit(2);
  }
  process.stdout.write(renderSudoers(parsePolicy(JSON.parse(readFileSync(path, "utf8")))));
}
